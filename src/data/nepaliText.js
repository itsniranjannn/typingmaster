const NEPALI_DIGITS = ["०", "१", "२", "३", "४", "५", "६", "७", "८", "९"];

const pick = (list) => list[Math.floor(Math.random() * list.length)];

const shuffled = (list) => {
  const copy = [...list];
  for (let i = copy.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
};

export const countWords = (text) => text.split(" ").filter(Boolean).length;

/** Several whole sentences until at least `minWords` words. */
export const getNepaliParagraph = (minWords = 30) => {
  const parts = [];
  let total = 0;
  for (const sentence of shuffled(NEPALI_SENTENCES)) {
    parts.push(sentence);
    total += countWords(sentence);
    if (total >= minWords) break;
  }
  return parts.join(" ");
};

/** `count` random words (no repeats until the list is exhausted). */
export const getNepaliWords = (count = 25) => {
  const out = [];
  while (out.length < count) {
    out.push(...shuffled(NEPALI_WORDS));
  }
  return out.slice(0, count).join(" ");
};

export const getNepaliQuote = () => pick(NEPALI_QUOTES);

export const getNepaliNumbers = (groups = 12) =>
  Array.from({ length: groups }, () => {
    const length = 2 + Math.floor(Math.random() * 4);
    return Array.from({ length }, () => pick(NEPALI_DIGITS)).join("");
  }).join(" ");

/** Extra text appended in endless/time mode. */
export const getNepaliChunk = () => getNepaliParagraph(12);
